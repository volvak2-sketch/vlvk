														<p>Sandblasting process is an abrasive collision stream having high kinetic energy, with the treated surface.</p>								
														<p>Sandblasting of surfaces is used, if necessary, clean any surfaces from rust, various types of plaque, the old multi-layer coatings, varnish and other contaminants. In some cases, in the process of sandblasting, there is destruction of the surface, it's not terrible, this fact indicates that this portion of the surface corrosion was too deep and the portion still to be repaired.</p>								
														<p>Sandblasting can be subjected to any surface: metal, concrete, masonry, natural stone, glass, wood, etc.</p>
														<p>Scope sandblasting quite extensive. With sandblasting possible industrial cleaning, cleaning of facades and buildings, vehicles, various containers, industrial and residential buildings and steel structures, various mechanisms and components.</p>
														<p>There are three types of sandblasting machines to perform various tasks on the sandblasted surfaces:</p>	
														<p>1. Sandblasts based on the principle of absorption.</p>
														<p>In these machines, air is used not only for the stream, but also in order to feed the material according to the injection nozzle to the container (without pressure). Such devices are used on light work of cleaning thin materials, the removal of paint residues, etc.</p>
														<p>2. Sandblasts vacuum type.</p>
														<p>In this structure, the abrasive grains are ejected onto the surface, followed by vacuum and taken up by re-run in the job. Such devices are used for sandblasting works on cleaning small areas in which the grains impact can cause damage to nearby units.</p>	
														<p>3. Pneumatic sandblasters.</p>
														<p>These devices are widely used for cleaning large surfaces or hard-to-structural elements: in shipyards, chemical plants, for cleaning buildings, bridges, steel or other structures having a large area.</p>
														<p>When sandblasting using quartz sand fines (0.5 - 0.1). Depending on the pressure and the quality of the abrasive, sandblasting gives a different surface roughness:</p>
														<p>1. Sandblasting effect, reminiscent of cleaning with a wire brush.</p>
														<p>2. Regular cleaning of the surface without the effect of gloss.</p>
														<p>3. Clean the surface of the metal surface almost to perfection.</p>
														<p>4. Clean the metal surface to full brightness.</p>
														<p>All modern paints require mandatory sandblasted surface treatment to give it roughness and removal of contaminants. Sandblasting method is the most effective of all existing methods of cleaning and surface preparation. Compared with an ordinary sander processing speed processing by sandblasting equipment is ten times higher.</p>
														<p>The preparation of the steel surface requirements include two important parameters: the surface shape and the degree of purification. As a result of research carried out by manufacturers of paints, it found that the adhesion and to guarantee an absolute protection of the substrate before coating is necessary to provide a corresponding shape. The notch provides dense uniform adhesion between the surface and the coating. When sandblasting waste materials are removed, clean surface hardened, angular abrasive particles roughen the surface and create a shape or a notch. The process of sandblasting the metal surface has a dual function: it cleans the surface and roughening the surface. Clean and rough surface is the perfect basis for engagement with the protective coating. Thus, pre-treatment of surfaces using sandblasting equipment is an economical method of providing the necessary basis for a primer coating.</p>
