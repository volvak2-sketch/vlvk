													<h4>Sandblasting</h4>	<br> 	
													
														<p>Sandblasting - a cold abrasive treatment of stone, glass, metal, etc. by damaging their surface with sand or other abrasive material, sprayed air flow.</p>
														<p>The first sandblasting method patented by American Benjamin Chu Tilgmanom in 1870. Since then, much has changed: sandblaster was improved, invented sandblasting camera, upgraded other blasting equipment. It remained unchanged but the principle of which consists in treating the surface of a material with sand or other abrasive material.</p>
