													<h4>Methods of corrosion control of metals</h4>	<br> 
													<p>Despite the apparent strength, metals are relatively easily broken under the influence of the external environment - air, water, acid, alkalis, salts, etc. Physico-chemical effects of metal with the environment, leading to its destruction, called corrosion. The term corrosion is derived from the Latin "corrosio", which means to corrode, destroy.</p>
													<div class="img-container">
														<img src="assets/images/protcor1.jpg" width="360" height="270">
													</div>	<br>
													<p>The process of destruction of metals under the influence of the environment is called atmospheric corrosion. Atmospheric corrosion is the most common type of corrosion, its manifestations are so numerous and varied that the improvement of methods of struggle against it do not lose its relevance.</p>
													<p>Atmospheric corrosion affects all steel structures operated outdoors: pipelines and tank equipment, metal parts of buildings, towers, bridges, vehicles, etc.</p>
													<p>Tanks are subjected during operation to corrosion, both from the outside and the inside. The outer surface of the tank is exposed to the so-called atmospheric corrosion and the inner surface corrodes under the influence of aggressive environment. And inside the tanks corrosive processes are more active. The speed and nature of the corrosion process is more pronounced in the areas of contact between the two media: mineral oil and produced water, petroleum and steam mixture.</p>
													<p>Currently, the high rate of industrial development, the intensification of production processes make high demands to the reliable operation of process equipment and building structures. A special place in the complex of measures to ensure the smooth operation of the equipment takes a reliable protection against corrosion. The need to implement measures for protection against corrosion caused by the fact that the losses from corrosion bring huge losses. There is evidence that about 10% of the annual metal production is consumed to cover losses from corrosion. The main damage by corrosion due not only to the loss of large quantities of metal, but also failure of steel structures themselves, as due to corrosion, they lose the necessary strength, flexibility, integrity, and other necessary qualities. And this in its turn leads to increased costs which include not only the cost of the cost of repairing damaged by corrosion of equipment, but also the cost of damages from various problems occurred due to corrosion. Part of these costs is inevitable, but can be significantly reduced through the use of continuous improvement and methods to protect against corrosion.</p>
													<p>Protect metals from corrosion damage consists of a series of measures to improve the efficiency and reliability of structures in the environment. Some of these measures is laid back in the design process, the part - in the process of manufacturing structures and other measures should be taken during the operation.</p>
													<p>There are various methods of corrosion control. The most popular are the interaction of metal corrosion control techniques with the environment at the boundary surface.</p>
													<p>For long-term storage of metal used organic type inhibitors. There are currently a lot of inhibitors and their use is expanding rapidly. They are used in chemical treatment of metals and conservation storage for long periods (containing inhibitors lubricant).</p>
													<p>For the protection of steel structures and equipment during their operation in practice of applied methods of protection against atmospheric corrosion of the most common and very effective method is the application of protective coatings.</p>
													<p>In the structure of the global cost of corrosion protection coatings to account for about 39% of the funds, which is 2 times higher than the costs of development and production of corrosion-resistant materials.</p>
													<p>The main advantages of coatings are:</p>
													<p>- The possibility of applying for protection of any designs directly on construction and assembly sites;</p>
													<p>- Simplicity and the possibility of mechanization of technological coating process;</p>
													<p>- Cover the majority of steel structures can be repaired and restored directly during operation;</p>
													<p>- Low consumption of material per unit area and low cost compared with other types of coatings.</p>
													<p>One of the key indicators in determining the effectiveness of the coating is its durability, those the ability to retain the protective properties to limit state when the installed system technology maintenance and repair.</p>					
													<p>Despite the progress made in the application of coatings, cases of their failure during a short operation are quite common. The main reasons for which are:</p>
													<p>1. Selection of the protective coating is carried out without taking into account the impact of climatic factors.</p>
													<p>2. When choosing a coating are preferred the most expensive (outdated) lacquer coating to initially incorporated short-lived life.</p>
													<p>3. Violation of protective coating technology.</p>
													<p>The main function of corrosion protection - to protect tanks and other metal from corrosion. The maximum effective corrosion protection of tanks is complex protection, those, protection of both internal and external surface of the tanks.</p>
													<p>The most effective protection against corrosion of up to 80% provided the proper surface preparation and only 20% use quality paints and the method of their application. The most efficient and effective method of surface preparation to further protect the surface is abrasive blasting.</p>
													<p>Today, protection of the internal tanks used bicomponent epoxy-based materials with a low content of solvents. The protective enclosure shall be impermeable to oil and its vapors, and is stable in contact with them. In addition, the protective coating must not affect the quality of the stored product.</p>
													<p>In my practice, Ltd. "CENTRREZERVUARSERVIS" is most often used for corrosion protection coatings such as:</p>
													<p>- Interline 859 - a protective electrically conductive two component, chemically resistant, high solids, high build coating phenol epoxy tanks. It is used to protect against corrosion of internal surfaces of tanks for storage of crude oil, unleaded gasoline, jet fuels, caustic solutions and a series of aromatic aliphatic solvents.</p>
													<p>- Intersil 670HS - especially two-component solid modified epoxy coating with high anti-corrosion properties. It is used to protect a wide range of substrates in a rigid aggressive environments, where high quality and longevity of the coating.</p>

