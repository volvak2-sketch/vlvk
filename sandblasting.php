													<p>3. Очищення металевої поверхні майже до блиску.</p> 
													<p>4. Очищення металевої поверхні до повного блиску.</p>
																										<p>Всі сучасні лакофарбові матеріали вимагають обов'язкової піскоструминної обробки поверхні для надання їй шорсткості та зняття забруднень. Піскоструминний спосіб є найбільш ефективним з усіх існуючих способів очищення та підготовки поверхонь. Порівняно зі звичайною обробкою шліфувальною машиною, швидкість обробки за допомогою піскоструминного обладнання в десятки разів вища.</p> 
													<p>Вимоги до підготовки сталевої поверхні включають два важливі параметри: профіль поверхні і ступінь очищення. Внаслідок досліджень, проведених виробниками лакофарбових матеріалів, виявлено, що для гарантованої адгезії та абсолютного захисту субстрату перед нанесенням покриття необхідно забезпечити відповідний профіль. Насікання забезпечує щільне однорідне зчеплення між поверхнею і покриттям. При піскоструминній обробці непотрібні матеріали видаляються, поверхня, що очищається, зміцнюється, незграбні частинки абразиву надають шорсткості поверхні і створюють профіль або насічку.</p> 
													<p>Процес піскоструминної обробки металевих поверхонь виконує подвійну функцію: він очищує поверхню і надає їй шорсткості. Очищена та шорстка поверхня є бездоганною основою для зчеплення із захисним покриттям. Таким чином, попередня обробка поверхні за допомогою піскоструминного обладнання є економічним методом, що забезпечує необхідну основу грунтовки для нанесення покриття.</p> 
