													<h4>Піскоструминна обробка</h4> <br> 
													<p> Піскоструминна обробка - це холодна абразивна обробка каменю, скла, металу і т.д. шляхом пошкодження їхньої поверхні піском або іншим абразивним матеріалом, що розпорошується потоком повітря.</p> 
													<p>Вперше метод піскоструминної обробки запатентований американцем Бенджаміном Чу Тілгманом у 1870 році. З того часу багато чого змінилося: було вдосконалено піскоструминний апарат, винайдено піскоструминну камеру, модернізовано інше піскоструминне обладнання. Незмінним залишився лише принцип роботи, який полягає у обробці поверхні того чи іншого матеріалу піском чи іншим абразивним матеріалом.</p> 
