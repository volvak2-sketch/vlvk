													</div> <br> 
													<p>Процес піскоструминної обробки є зіткненням потоку абразивного матеріалу, що володіє високою кінетичною енергією, з оброблюваною поверхнею.</p> 

													<p>Піскоструминна обробка поверхонь застосовується у разі необхідності очищення будь-яких поверхонь від іржі, різних видів нальоту, старих багатошарових лакофарбових покриттів, нагару та інших забруднень. У деяких випадках, у процесі піскоструминної обробки, спостерігається руйнування частини поверхні, це не страшно, цей факт говорить про те, що на цій ділянці поверхні корозія була надто глибокою і ця ділянка все одно підлягає ремонту.</p> 
													<p>Піскоструминну обробку можна піддавати будь-які поверхні: метал, бетон, цегляна кладка, природний камінь, скло, дерево і т.д.</p> 
													<p>Область застосування піскоструминної обробки досить велика. За допомогою піскоструминки можливе промислове прибирання, очищення фасадів та будівель, автотранспорту, різних ємностей, промислових та побутових металоконструкцій та споруд, різних механізмів та деталей.</p> 
													<p>Для виконання різних робіт з піскоструминної обробки поверхонь існують три види піскоструминних апаратів:</p> 
													<p>1. Піскоструминні апарати, засновані на принципі всмоктування.</p> 
													<p>У цих машинах повітря використовується не тільки для струменя, а й для того, щоб подати матеріал за принципом інжекції від контейнера до сопла (без використання тиску). Такі апарати застосовуються на легких роботах з очищення тонких матеріалів, видалення залишків фарби тощо.</p> 
													<p>2. Піскоструминні апарати вакуумного типу.</p> 
													<p>У цій конструкції зерна абразиву викидаються на оброблювану поверхню, потім за допомогою вакууму підхоплюються і повторно запускаються в роботу. Такі апарати застосовуються під час піскоструминних робіт з очищення невеликих площ, на яких вплив зерен може призвести до пошкодження прилеглих пристроїв.</p> 
													<p>3. Пневматичні піскоструминні апарати.</p> 
													<p>Ці апарати широко використовуються для очищення великих площ або складних елементів конструкцій: на корабельних верфях, хімічних заводах, при очищенні будівель, мостів, сталевих або інших конструкцій, що мають велику площу.</p> 
