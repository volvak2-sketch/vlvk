													<p>3. Порушення технології нанесення захисних покриттів.</p> 
													<p>Основна функція антикорозійного захисту – вберегти цистерни, резервуари та інші металоконструкції від впливу агресивного середовища. Максимально ефективним антикорозійним захистом резервуарів є комплексний захист, тобто. захист як внутрішньої, так і зовнішньої поверхні резервуарів.</p> 
													<p>Найбільш ефективний захист від корозії на 80% забезпечується правильною підготовкою поверхні і тільки на 20% якістю лакофарбових матеріалів, що використовуються, і способом їх нанесення. Найпродуктивнішим і найефективнішим методом підготовки поверхні для подальшого захисту поверхні є абразивоструйна обробка.</p> 
													<p>Сьогодні для внутрішнього захисту резервуарів використовуються двокомпонентні матеріали на епоксидній основі з низьким вмістом розчинників. Захисна оболонка повинна бути непроникною для нафтопродукту та його пари та стабільна в контакті з ними. Крім того, захисне покриття не повинно впливати на якість продукту, що зберігається.</p> 
